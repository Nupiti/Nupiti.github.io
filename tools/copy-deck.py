#!/usr/bin/env python3
"""
Make a COPY DECK: every piece of text on the website, in reading order, with the
exact file and line (or data field) where it lives.

Usage:  python tools/copy-deck.py
Writes: COPY-DECK.txt in the folder above the site (next to your CV).

Read it like a proof. Mark what you want changed, then either edit at the place
shown or send the marked-up file back to be applied.
"""
import html as htmllib
import json
import os
import re

SITE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(os.path.dirname(SITE), "COPY-DECK.txt")

PAGES = [
    ("index.html", "HOME"),
    ("research.html", "RESEARCH"),
    ("publications.html", "PUBLICATIONS"),
    ("photography.html", "PHOTOGRAPHY"),
    ("life.html", "LIFE"),
    ("writing.html", "WRITING"),
]

out = []
W = lambda s="": out.append(s)


def clean(s):
    s = re.sub(r"<!--.*?-->", "", s, flags=re.S)
    s = re.sub(r"<br\s*/?>", " / ", s)
    s = re.sub(r"<[^>]+>", "", s)
    s = htmllib.unescape(s)
    return re.sub(r"\s+", " ", s).strip()


def kind(tag, attrs):
    if "eyebrow" in attrs or "hero__kicker" in attrs:
        return "label"
    if tag == "h1":
        return "page title"
    if tag in ("h2", "h3"):
        return "heading"
    if "quote" in attrs and tag == "blockquote":
        return "pull quote"
    if "lede" in attrs or "hero__statement" in attrs:
        return "opening line"
    if "fact__value" in attrs:
        return "fact number"
    if "fact__label" in attrs:
        return "fact label"
    if "row__key" in attrs:
        return "row label"
    if "row__val" in attrs:
        return "row text"
    if "strip__cap" in attrs or "split__cap" in attrs or "hero__frame-cap" in attrs or "hero__inset-cap" in attrs:
        return "photo caption"
    if "card__num" in attrs:
        return "card number"
    if "btn" in attrs or "link-out" in attrs:
        return "button / link"
    if "hero__meta" in attrs:
        return "hero meta"
    if tag == "li":
        return "chip"
    if tag == "p":
        return "text"
    return None


W("SUMITH ABEYKOON — WEBSITE COPY DECK")
W("=" * 78)
W()
W("Every piece of text on the site, in reading order, with the file and line number")
W("(or the data file and field) where it lives.")
W()
W("HOW TO USE THIS")
W("  - Read it through. Mark anything you want changed, right here in this file.")
W("  - Send it back and the changes get applied, or edit at the location shown.")
W("  - Text marked [data: ...] lives in a JSON file in site/data/. Those are the")
W("    files you will edit yourself over the years, so they are worth knowing.")
W()
W("Generated by tools/copy-deck.py from the current site files. Re-run it any time.")

# ---------------------------------------------------------------- HTML pages
for page, title in PAGES:
    path = os.path.join(SITE, page)
    if not os.path.exists(path):
        continue
    lines = open(path, encoding="utf-8").read().split("\n")
    W(); W(); W("=" * 78); W(f"PAGE: {title}   ({page})"); W("=" * 78)
    in_footer = in_nav = False
    seen = set()
    for i, line in enumerate(lines, 1):
        if "<footer" in line: in_footer = True
        if "</footer>" in line: in_footer = False
        if '<nav class="nav"' in line: in_nav = True
        if "</nav>" in line: in_nav = False; continue
        if in_footer or in_nav: continue
        if 'class="brand"' in line or "skip-link" in line: continue

        for m in re.finditer(r"<(h1|h2|h3|p|span|blockquote|div|li|a)\b([^>]*)>(.*?)</\1>", line):
            tag, attrs, inner = m.group(1), m.group(2), m.group(3)
            txt = clean(inner)
            if not txt or len(txt) < 2 or txt in seen: continue
            k = kind(tag, attrs)
            if not k: continue
            if tag == "a" and ("btn" not in attrs and "link-out" not in attrs): continue
            if tag == "span" and k == "text": continue
            seen.add(txt)
            if k in ("label", "chip", "row label", "fact number", "fact label", "card number", "hero meta", "button / link", "photo caption"):
                W(f"  [{k} · line {i}]  {txt}")
            else:
                W(f"\n  [{k} · line {i}]"); W(f"    {txt}")

# ---------------------------------------------------------------- data files
D = os.path.join(SITE, "data")

def section(title, note):
    W(); W(); W("=" * 78); W(title); W("=" * 78); W(note)

try:
    d = json.load(open(os.path.join(D, "research-notes.json"), encoding="utf-8"))
    section("DATA: RESEARCH HIGHLIGHTS   (data/research-notes.json)",
            "The scientific feed on the Research page, and the three newest on the home page.")
    for n, x in enumerate(d.get("notes", []), 1):
        W(f"\n  [note {n} · {x.get('tag','')} · {x.get('date','')}]")
        W(f"    TITLE: {x.get('title','')}")
        W(f"    BODY:  {x.get('body','')}")
        if x.get("link"): W(f"    LINK:  {x['link']}")
except Exception as e:
    W(f"  (could not read research-notes.json: {e})")

try:
    d = json.load(open(os.path.join(D, "publications.json"), encoding="utf-8"))
    section("DATA: PUBLICATION THEMES   (data/publications.json → themes)",
            "The plain-language summary above each group of papers. Paper titles themselves are not listed here.")
    for t in d.get("themes", []):
        W(f"\n  [theme · {t.get('label','')}]")
        W(f"    TITLE:   {t.get('title','')}")
        for para in t.get("summary", "").split("\n\n"):
            W(f"    SUMMARY: {para}")
except Exception as e:
    W(f"  (could not read publications.json: {e})")

try:
    d = json.load(open(os.path.join(D, "photos.json"), encoding="utf-8"))
    section("DATA: PHOTOGRAPHY SESSIONS   (data/photos.json)",
            "Each session's title, place line, note, and every photo caption.")
    for s in d.get("sessions", []):
        W(f"\n  [session]  {s.get('title','')}   ·   {s.get('place','')}")
        W(f"    NOTE: {s.get('note','')}")
        for p in s.get("photos", []):
            W(f"    {'PICK ' if p.get('pick') else '     '}{p.get('file',''):22} {p.get('caption','')}")
except Exception as e:
    W(f"  (could not read photos.json: {e})")

try:
    d = json.load(open(os.path.join(D, "beamtimes.json"), encoding="utf-8"))
    section("DATA: BEAMTIMES   (data/beamtimes.json)", "Timeline on the Research page; count on the home page.")
    for b in d.get("campaigns", []):
        W(f"    {b.get('when',''):10} {b.get('facility',''):18} {b.get('what','')}" + (f"  · {b['code']}" if b.get("code") else ""))
except Exception as e:
    W(f"  (could not read beamtimes.json: {e})")

text = "\n".join(out) + "\n"
open(OUT, "w", encoding="utf-8").write(text)
print(f"Wrote {OUT}  ({len(out)} lines)")
